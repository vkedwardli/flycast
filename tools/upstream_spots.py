"""Check that every changed spot in an upstream file is marked and listed.

A spot is a diff hunk of an upstream file against the fork point (working tree,
fork-only files and third-party code excluded). It is marked when an added
line, or the line above it, contains "gdxsv". Its description is the first
"// gdxsv: <why>" comment, else the gdxsv include or names it adds.

The list of spots in docs/gdxsv/upstream.md (between the "upstream_spots"
comments) is generated from the markers. Exit 1 when a spot is not marked or
the list is not up to date; --write rewrites the list.

  tools/upstream_spots.py [--base REV] [--write] [--all]

--base defaults to the merge base of upstream master and HEAD (fetched).
"""
import argparse
import re
import subprocess
import sys

UPSTREAM = "https://github.com/flyinghead/flycast.git"
DOC = "docs/gdxsv/upstream.md"
BEGIN = "<!-- upstream_spots begin: generated by tools/upstream_spots.py --write -->"
END = "<!-- upstream_spots end -->"
# Paths that are the fork's own or third-party; not upstream Flycast code.
SKIP = (":!core/gdxsv", ":!core/deps", ":!tests", ":!tools", ":!docs",
        ":!gdxsv_patch", ":!gdxsv_langmod", ":!resources", ":!.github",
        ":!*.md", ":!*.pdf", ":!run.py", ":!gdxsv-format.sh", ":!.gitmodules")
HUNK = re.compile(r"^@@ -\d+(?:,\d+)? \+(\d+)(?:,\d+)? @@ ?(.*)$")
WHY = re.compile(r"(?://|#)\s*gdxsv:\s*(.*)")
INCLUDE = re.compile(r'#include\s+"(gdxsv/[^"]+)"')
NAME = re.compile(r"settings\.gdxsv\.\w+|\b\w*[gG]dxsv\w*")
KEYWORDS = {"if", "elseif", "else", "endif", "foreach", "while", "for", "switch",
            "find_package", "option", "set", "target_sources", "target_link_libraries"}


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True,
                          text=True, encoding="utf-8", errors="replace").stdout


def describe(lines):
    for i, line in enumerate(lines):
        m = WHY.search(line)
        if not m:
            continue
        # The comment goes on over the next comment-only lines; keep its
        # first sentence.
        text = m.group(1).strip()
        for cont in lines[i + 1:]:
            c = re.match(r"\s*(?://|#(?![a-z]))\s*(.*)", cont)
            if not c or WHY.search(cont) or re.search(r"\.\s*$", text):
                break
            text += " " + c.group(1).strip()
        sentence = re.match(r"(.*?\.)(?:\s|$)", text)
        return sentence.group(1) if sentence else text
    for line in lines:
        m = INCLUDE.search(line)
        if m:
            return f"include `{m.group(1)}`"
    names = []
    for line in lines:
        for n in NAME.findall(line):
            if n != "gdxsv" and n not in names:
                names.append(n)
    if names:
        return ", ".join(f"`{n}`" for n in names[:3])
    line = next(l for l in lines if "gdxsv" in l.lower()).strip()
    return f"`{line[:100]}`"


def where(context):
    # git's hunk context is the last line before the hunk that starts a
    # function or block. Keep a function name; a declaration or a CMake
    # command says nothing about where the spot is.
    m = re.search(r"([\w:~]+)\s*\(", context)
    if not m or context.rstrip().endswith(";") or m.group(1) in KEYWORDS:
        return ""
    return f"`{m.group(1)}`"


def spots(base):
    added = set(git("diff", "--name-only", "--diff-filter=A", base, "--", ".", *SKIP).split())
    out = git("diff", "-U1", base, "--", ".", *SKIP)
    path, cur, found = None, None, []
    for line in out.splitlines():
        if line.startswith("+++ "):
            path = line[6:] if line.startswith("+++ b/") else None
            continue
        if path is None or path in added:
            continue
        m = HUNK.match(line)
        if m:
            cur = {"path": path, "line": int(m.group(1)), "where": where(m.group(2)),
                   "prev": "", "text": [], "changed": False}
            found.append(cur)
            continue
        if cur is None or line.startswith(("diff ", "index ", "--- ")):
            continue
        if line.startswith(("+", "-")):
            if not cur["changed"] and "gdxsv" in cur["prev"].lower():
                cur["text"].append(cur["prev"])
            cur["changed"] = True
            if line.startswith("+"):
                cur["text"].append(line[1:])
        elif not cur["changed"]:
            cur["prev"] = line[1:]
    for s in found:
        s["marked"] = any("gdxsv" in l.lower() for l in s["text"])
        s["what"] = describe(s["text"]).replace("|", "\\|") if s["marked"] else ""
        # A changed function signature: the spot is in that function, not in
        # the one git names before it.
        first = next((l for l in s["text"] if l.strip() and not l.lstrip().startswith("//")), "")
        if re.match(r"\w[^;]*\)\s*$", first):
            s["where"] = where(first) or s["where"]
    return found


def table(found):
    rows = ["| File | Where | What |", "|---|---|---|"]
    for s in found:
        if s["marked"]:
            rows.append(f'| `{s["path"]}` | {s["where"]} | {s["what"]} |')
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base")
    ap.add_argument("--write", action="store_true", help=f"rewrite the list in {DOC}")
    ap.add_argument("--all", action="store_true", help="print every spot, not only the unmarked")
    a = ap.parse_args()
    base = a.base
    if not base:
        git("fetch", "-q", UPSTREAM, "master")
        base = git("merge-base", "FETCH_HEAD", "HEAD").strip()
    found = spots(base)
    bad = 0
    for s in found:
        if a.all or not s["marked"]:
            flag = "ok " if s["marked"] else "NO "
            print(f'{flag}{s["path"]}:{s["line"]} {s["where"]} {s["what"]}')
        bad += not s["marked"]

    with open(DOC, encoding="utf-8", newline="") as f:
        doc = f.read()
    head, sep, rest = doc.partition(BEGIN + "\n")
    old, sep2, tail = rest.partition(END)
    if not sep or not sep2:
        print(f"{DOC}: no {BEGIN} ... {END} section")
        return 1
    new = table(found) + "\n"
    stale = old != new
    if stale and a.write:
        with open(DOC, "w", encoding="utf-8", newline="") as f:
            f.write(head + BEGIN + "\n" + new + END + tail)
        stale = False
    print(f"{len(found)} spots, {bad} unmarked, base {base[:10]}, list {'stale (--write)' if stale else 'up to date'}")
    return 1 if bad or stale else 0


if __name__ == "__main__":
    sys.exit(main())
